local function week_header(concat)
	local week = week_ascii_text()
	local daysoftheweek = {
		"Sunday",
		"Monday",
		"Tuesday",
		"Wednesday",
		"Thursday",
		"Friday",
		"Saturday",
	}
	local day = daysoftheweek[os.date("*t").wday]
	local tbl = week[day]
	local art = ""

	table.insert(tbl, 1, "⫸  " .. (vim.fn.expand("%:p:h:t") or "") .. " ⫷-")
	table.insert(tbl, os.date("%Y-%m-%d %H:%M:%S ") .. (concat or ""))

	for i = 1, table.maxn(tbl), 1 do
		art = art .. tbl[i] .. "\n"
	end

	return art
end

